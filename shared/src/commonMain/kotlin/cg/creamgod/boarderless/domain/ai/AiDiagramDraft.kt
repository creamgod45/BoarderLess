internal data class AiDiagramCapabilities(
    val shapes: Set<NodeShape>,
    val nodeColors: Set<String>,
    val groupColors: Set<String>,
    val selfLoops: Boolean = false,
)

internal data class AiDiagramToolCall(
    val requestId: String,
    val sessionId: String,
    val callId: String,
    val name: String,
    val arguments: String,
)

internal enum class AiDiagramToolStatus { Read, Proposed, Rejected }

internal enum class AiDiagramToolFailure { Scope, Closed, DuplicateCall, UnknownTool, Schema, Limit, Locked, Dependency, Unsupported, Internal }

internal data class AiDiagramToolResult(
    val callId: String?,
    val status: AiDiagramToolStatus,
    val data: JsonObject = JsonObject(emptyMap()),
    val failure: AiDiagramToolFailure? = null,
)

private class DraftRejected(
    val code: AiDiagramToolFailure,
) : IllegalArgumentException("AI diagram tool rejected")

